// Generates src/io/pdfCMapData.ts: the Korean predefined CMaps from the pinned
// pdfjs-dist, base64-embedded so PDF import never reads CMaps from disk or network.
// Run automatically by `npm run gen-assets`. Output is byte-stable for a given pdfjs-dist.
import { promises as fs } from "node:fs";
import * as path from "node:path";

const root = process.cwd();
const cmapDir = path.join(root, "node_modules", "pdfjs-dist", "cmaps");
const pdfjsPackage = JSON.parse(
  await fs.readFile(path.join(root, "node_modules", "pdfjs-dist", "package.json"), "utf8")
);
const KOREAN_CMAP = /^(?:Adobe-Korea1-(?:0|1|2|UCS2)|KSC(?:-EUC|-Johab|ms-UHC|ms-UHC-HW|pc-EUC)?-[HV]|KSC-[HV]|UniKS-(?:UCS2|UTF8|UTF16|UTF32)-[HV])\.bcmap$/;

const names = (await fs.readdir(cmapDir)).filter((name) => KOREAN_CMAP.test(name)).sort();
if (names.length !== 24) {
  throw new Error(`Expected 24 Korean CMaps in pdfjs-dist ${pdfjsPackage.version}, found ${names.length}.`);
}

let total = 0;
let out =
  "// AUTO-GENERATED by scripts/gen-pdf-cmaps.mjs — do not edit by hand.\n" +
  `// Korean predefined CMaps from pdfjs-dist ${pdfjsPackage.version} (Adobe CMap resources; see THIRD_PARTY_NOTICES.md).\n` +
  "export const PDF_CMAP_BASE64: Readonly<Record<string, string>> = {\n";
for (const name of names) {
  const bytes = await fs.readFile(path.join(cmapDir, name));
  total += bytes.byteLength;
  out += `  ${JSON.stringify(name.replace(/\.bcmap$/, ""))}: ${JSON.stringify(bytes.toString("base64"))},\n`;
}
out += "};\n";

await fs.writeFile(path.join(root, "src", "io", "pdfCMapData.ts"), out, "utf8");
console.log(`Embedded ${names.length} Korean PDF CMaps (${(total / 1024).toFixed(1)} KB) → src/io/pdfCMapData.ts`);
