// Generates src/io/formTemplateData.ts: the two standard draft-letter forms that Kordoc
// ships in node_modules/kordoc/templates (rhwp tools/forms, MIT). HanMark embeds the bytes
// instead of calling Kordoc's filesystem reader, so the bundle needs no file access.
// Run automatically by `npm run build` / `npm run dev`.
import { promises as fs } from "node:fs";
import * as path from "node:path";

const root = process.cwd();
const templates = path.join(root, "node_modules", "kordoc", "templates");
const FORMS = [
  { id: "gian", file: "일반기안문_서식.hwpx" },
  { id: "gian-simple", file: "간이기안문_서식.hwpx" }
];

let out =
  "// AUTO-GENERATED by scripts/gen-form-templates.mjs — do not edit by hand.\n" +
  "// Standard draft-letter forms (별지 제1·2호서식) from rhwp tools/forms, MIT license,\n" +
  "// as redistributed by Kordoc. See THIRD_PARTY_NOTICES.md.\n" +
  "export const BUILTIN_FORM_BASE64: Readonly<Record<\"gian\" | \"gian-simple\", string>> = {\n";
let total = 0;
for (const form of FORMS) {
  const bytes = await fs.readFile(path.join(templates, form.file));
  if (bytes.subarray(0, 2).toString("latin1") !== "PK") throw new Error(`${form.file} is not an HWPX (ZIP) file`);
  total += bytes.byteLength;
  out += `  ${JSON.stringify(form.id)}: ${JSON.stringify(bytes.toString("base64"))},\n`;
}
out += "};\n";
await fs.writeFile(path.join(root, "src", "io", "formTemplateData.ts"), out, "utf8");
console.log(`Embedded ${FORMS.length} standard forms (${(total / 1024).toFixed(1)} KB) → src/io/formTemplateData.ts`);
